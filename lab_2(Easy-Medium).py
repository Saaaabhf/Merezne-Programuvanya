# Підключаємо Flask для створення сервера та request для читання адресного рядка
from flask import Flask, request

# Створюємо саму програму (наш веб-сервер)
app = Flask(__name__)

# Завдання [Easy]: Якщо хтось зайде на головну сторінку "/", сервер віддасть текст "Hello World!"
@app.route('/', methods=['GET'])
def hello_world():
    return "Hello World!"

