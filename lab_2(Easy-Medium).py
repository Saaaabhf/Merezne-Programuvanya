# Ця умова перевіряє, що ми запускаємо саме цей файл, а не імпортуємо його кудись
if __name__ == '__main__':
    # Запускаємо сервер, щоб він працював і чекав на підключення
    # host='127.0.0.1' означає, що сервер доступний тільки на цьому комп'ютері (локально)
    # port=8000 - це порт, який вимагали у завданні
    app.run(host='127.0.0.1', port=8000)
